import type { AppFunctionsModel } from '../model';
import { XML_HEADER, escapeAndroidString, escapeXmlAttr } from './shared';

export const APP_METADATA_RES = 'appfunctions_app_metadata';
export const DISPLAY_DESCRIPTION_STRING = 'appfunctions_display_description';

export function hasAppMetadata(m: AppFunctionsModel): boolean {
  return (
    m.appDescription !== undefined || m.appDisplayDescription !== undefined
  );
}

/** Manifest overlay merged into the app by AGP (`addGeneratedManifestFile`). */
export function manifestFile(m: AppFunctionsModel): string {
  const metadataProperty = hasAppMetadata(m)
    ? `
        <property
            android:name="android.app.appfunctions.app_metadata"
            android:resource="@xml/${APP_METADATA_RES}" />
`
    : '';
  return `<?xml version="1.0" encoding="utf-8"?>
${XML_HEADER}
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools">

    <application>
        <!-- ${m.serviceName} and its XML assets are generated by KSP from ${m.baseClassName}. -->
        <service
            android:name="${m.kotlinPackage}.${m.serviceName}"
            android:permission="android.permission.BIND_APP_FUNCTION_SERVICE"
            android:exported="true"
            tools:targetApi="36">
            <property
                android:name="android.app.appfunctions.schema"
                android:value="app_functions_schema.xsd" />
            <property
                android:name="android.app.appfunctions.v2"
                android:value="${m.xmlFileName}.xml" />
            <!-- Legacy (v1) indexer, read by Android 16 builds. -->
            <property
                android:name="android.app.appfunctions"
                android:value="${m.xmlFileName}-v1.xml" />
            <intent-filter>
                <action android:name="android.app.appfunctions.AppFunctionService" />
            </intent-filter>
        </service>
${metadataProperty}    </application>
</manifest>
`;
}

/** `res/xml/appfunctions_app_metadata.xml` */
export function appMetadataFile(m: AppFunctionsModel): string {
  const attrs = [
    ...(m.appDescription !== undefined
      ? [`appfn:description="${escapeXmlAttr(m.appDescription)}"`]
      : []),
    ...(m.appDisplayDescription !== undefined
      ? [`appfn:displayDescription="@string/${DISPLAY_DESCRIPTION_STRING}"`]
      : []),
  ];
  return `<?xml version="1.0" encoding="utf-8"?>
${XML_HEADER}
<AppFunctionAppMetadata xmlns:appfn="http://schemas.android.com/apk/androidx.appfunctions"
${attrs.map((a) => `    ${a}`).join('\n')} />
`;
}

/** `res/values/appfunctions_strings.xml` */
export function stringsFile(m: AppFunctionsModel): string {
  return `<?xml version="1.0" encoding="utf-8"?>
${XML_HEADER}
<resources>
    <string name="${DISPLAY_DESCRIPTION_STRING}">${escapeAndroidString(m.appDisplayDescription ?? '')}</string>
</resources>
`;
}
